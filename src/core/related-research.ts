import type { WorkUnit } from "./types";

// A runtime requirement as well as an editable bundled writing rule. Older task
// snapshots/custom writing rules must not make adversarial reviewers miss this
// check. Use the existing concern/repair protocol, not another receipt schema.
export function relatedResearchGuidance(unit: WorkUnit, sharedWritingRevision?: string): string {
  const role = unit.role === "reviewer"
    ? "敵対レビュー：各逐次・並列独立・クロス検証で、自ら原論文と全主要主張を照合する。前担当の合格や照合表は証明にしない。数値・性能比較・優位性・新規性、反例・省略された制約を精査する。読み取り専用を守り、誤記・根拠不足・未確認をconcernsと関連達成条件のfail/unverifiedへ具体的に記す。通常修正はnextAction=repairと指示でワーカーへ戻す。evidenceは既存ファイル、URL/原論文の箇所はdetailへ記す。"
    : unit.planPhase || unit.role === "planner"
      ? "計画：関連研究を紹介する成果物では、紹介内容の一次資料照合を執筆担当の作業と独立・敵対レビューの両方に組み込む。既存の異種AI二重チェックを利用し、書誌情報の確認だけで内容確認済みとしない。新たな権限や不要な研究工程は増やさない。"
      : "執筆・調査・仕上げ：紹介文を書く前と修正後に原論文と照合する。書き込み可能な担当は主張と出典の対応を小さな検証記録に整理し、後続レビューへ渡す。読み取り専用担当はファイルを作らず引き継ぎに記す。レポーターは自分の確認と後続の独立レビューを区別し、後続レビューの未実施だけを理由に待機しない。";
  const heading = "# 関連研究の内容忠実性チェック（書誌情報とは別・必須）";
  const reuse = "一次資料再利用：書き込み担当が一次資料を一度保存（URL/DOI・公開版・取得日・ハッシュ）し、異種AIは同じ版を独立に読む。共有するのは原資料だけで、先行結論は含めない。読み取り専用担当は保存を代行しない。公開版とプレプリントを同一と推測しない。403/タイムアウトは同じURLへこの担当で原則2回まで。許可された別の一次資料を探すか取得不能/版不一致を記録し、他作業を進める。要旨だけで本文確認済みにしない。資料・紹介文が変わらない有効結果は再利用し、変更部分だけ再照合する。必須条件の未確認は合格にしない。";
  if (sharedWritingRevision) return [heading, role, reuse,
    `照合する主張・一次資料・根拠箇所・判定の詳細は、同じ実行のwriting-rules（版 ${sharedWritingRevision}）の「関連研究の内容忠実性チェック」を読む。書誌情報の二重照合とは別に行い、本文を取得できなければ未確認として報告する。`
  ].join("\n");
  return [heading,
    reuse,
    "文書で紹介・比較した研究がある場合に適用する。各主張を、引用した版の原論文本文・図表・数式・実験設定・補足資料の該当箇所と照合する。検索要約、タイトル、要旨、第三者の解説やAIの記憶だけで内容を確定しない。研究目的、実際の提案手法、仮定・対象範囲、実験条件・比較対象・指標・数値、結果と限界が正しく伝わるか確認する。他研究との取り違え、提案と実証の混同、著者の主張と自分の推論の混同、限定的結果の一般化、条件の異なる性能値の単純比較を検出し、断定の強さを原論文に合わせる。",
    role,
    "照合の証跡は紹介文の箇所・文献キー・要約した主張・一次資料のURL/DOIと版・ページ/節/図表等・判定と相違点を対応づける。ページ番号や読んだ事実を捏造しない。本文未取得や曖昧さは未確認として残し、承認範囲内で出典の再取得・主張の限定や訂正を行う。引用先・紹介内容を直したら影響箇所を再確認する。管理用照合記録を主題の本文・付録に混ぜず、本文には必要な引用と科学的な留保を残す。紹介した研究がない場合は対象なしとし、この検査のためだけに文献を増やさない。"
  ].join("\n");
}
